CREATE TABLE game_round_record (
    id BIGINT NOT NULL AUTO_INCREMENT,
    user_id BINARY(16) NOT NULL,
    session_id BINARY(16) NOT NULL,
    round_key VARCHAR(128) NOT NULL,
    game_uin BIGINT NOT NULL,
    scene_id INT NOT NULL,
    room_id INT NOT NULL,
    table_id INT NOT NULL,
    local_seat_id INT NOT NULL,
    landlord_seat_id INT NOT NULL,
    multiplier INT NOT NULL,
    bean_change BIGINT NOT NULL,
    beans_after BIGINT NOT NULL,
    factor BIGINT NOT NULL,
    result VARCHAR(16) NOT NULL,
    detail_json LONGTEXT NOT NULL,
    finished_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_game_round_record_key UNIQUE (session_id, round_key),
    CONSTRAINT fk_game_round_record_user FOREIGN KEY (user_id) REFERENCES app_user(id) ON DELETE CASCADE,
    CONSTRAINT fk_game_round_record_session FOREIGN KEY (session_id) REFERENCES game_client_session(id) ON DELETE CASCADE,
    INDEX idx_game_round_record_user_time (user_id, finished_at)
);
